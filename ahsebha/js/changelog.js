// مقارنة رقمين من الشكل 1.6.0: سالب إن كان a أقدم من b، صفر إن تساويا، موجب إن كان a أحدث
export function cmpVersion(a, b) {
  const x = String(a).split('.').map(Number);
  const y = String(b).split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    const d = (x[i] || 0) - (y[i] || 0);
    if (d) return d;
  }
  return 0;
}

